#[test]
fn test_canonical_text_ignores_layout_comments_and_docs() {
    let text = |source: &str| canonical(source.parse().unwrap());
    assert_eq!(
        text("fn a(x: u32, y: u32) -> [u32; 2] { [x, y] }"),
        text(
            "/// doc\n#[doc = \"more\"]\nfn a(\n    x: u32,\n    y: u32, // note\n) -> [u32; 2] {\n    /* c */ [\n        x,\n        y,\n    ]\n}"
        ),
    );
    assert_eq!(text("S { a: 1 }"), text("S { a: 1, }"));
    assert_ne!(text("let t = (a,);"), text("let t = (a);"));
}

