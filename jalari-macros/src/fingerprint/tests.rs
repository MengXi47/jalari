#[test]
fn test_fallback_hashes_the_whole_workspace() {
    let rest = "fn helper() -> u32 { 1 }\nfn other() -> u32 { 1 }";
    let base = single(&[("src/lib.rs", &source("helper();", rest))]);
    let edited = single(&[(
        "src/lib.rs",
        &source(
            "helper();",
            &rest.replace("other() -> u32 { 1 }", "other() -> u32 { 2 }"),
        ),
    )]);
    assert_ne!(whole(&base, None, VERSION), of(&base));
    assert_ne!(whole(&base, None, VERSION), whole(&edited, None, VERSION));
    assert_ne!(whole(&base, None, "0.5.0"), whole(&base, None, "0.6.0"));
    assert_eq!(
        whole(&base, None, VERSION),
        whole(&base, Some("src/elsewhere.rs"), VERSION)
    );
}

