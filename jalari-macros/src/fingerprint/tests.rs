fn source(body: &str, rest: &str) -> String {
    format!(
        "use jalari::{{Job, JobResult}};

#[derive(Serialize, Deserialize)]
struct J {{
    count: u32,
}}

#[jalari::job]
impl Job for J {{
    const NAME: &'static str = \"j\";

    async fn run(self) -> JobResult {{
        {body}
        Ok(())
    }}
}}

{rest}
"
    )
}

fn crate_source(package: &str, roots: &[&str], files: &[(&str, &str)]) -> CrateSource {
    CrateSource {
        package: package.to_owned(),
        roots: roots.iter().map(|root| (*root).to_owned()).collect(),
        files: files
            .iter()
            .map(|(path, content)| ((*path).to_owned(), (*content).to_owned()))
            .collect(),
        deps: BTreeMap::new(),
    }
}

fn single(files: &[(&str, &str)]) -> Workspace {
    Workspace {
        crates: vec![crate_source("app", &["src/lib.rs", "src/main.rs"], files)],
        lock: None,
    }
}

fn with_shared(app_lib: &str, shared_lib: &str) -> Workspace {
    let mut workspace = single(&[("src/lib.rs", app_lib)]);
    workspace.crates[0]
        .deps
        .insert("shared".to_owned(), Dependency::Path(1));
    workspace.crates.push(crate_source(
        "shared",
        &["src/lib.rs"],
        &[("src/lib.rs", shared_lib)],
    ));
    workspace
}

fn with_registry(app_lib: &str, lock: &str) -> Workspace {
    let mut workspace = single(&[("src/lib.rs", app_lib)]);
    for name in ["serde_json", "reqwest", "itoa"] {
        workspace.crates[0]
            .deps
            .insert(name.to_owned(), Dependency::Registry(name.to_owned()));
    }
    workspace.lock = Some(Lock::parse(lock));
    workspace
}

fn macro_input(workspace: &Workspace, file: &str, self_ty: &str) -> syn::ItemImpl {
    find_job(&workspace.crates[0].files[file], self_ty)
}

fn find_job(text: &str, self_ty: &str) -> syn::ItemImpl {
    jobs_in(text)
        .into_iter()
        .find(|item| item.self_ty.to_token_stream().to_string() == self_ty)
        .expect("job impl present")
}

fn jobs_in(text: &str) -> Vec<syn::ItemImpl> {
    let Ok(parsed) = syn::parse_file(text) else {
        return Vec::new();
    };
    let mut finder = Finder::default();
    finder.visit_file(&parsed);
    finder.found
}

#[derive(Default)]
struct Finder {
    found: Vec<syn::ItemImpl>,
}

impl<'ast> Visit<'ast> for Finder {
    fn visit_item_impl(&mut self, item_impl: &'ast syn::ItemImpl) {
        let is_job_attribute = |attribute: &syn::Attribute| {
            attribute
                .path()
                .segments
                .last()
                .is_some_and(|segment| segment.ident == "job")
        };
        if is_job_impl(item_impl) && item_impl.attrs.iter().any(is_job_attribute) {
            let mut item = item_impl.clone();
            item.attrs.retain(|attribute| !is_job_attribute(attribute));
            self.found.push(item);
        }
        syn::visit::visit_item_impl(self, item_impl);
    }
}

fn job_at(workspace: &Workspace, file: &str, self_ty: &str, version: &str) -> u128 {
    let item = macro_input(workspace, file, self_ty);
    fingerprint(
        &Index::build(workspace),
        workspace,
        &JobSite {
            item: &item,
            file: Some(file),
        },
        version,
    )
}

fn of(workspace: &Workspace) -> u128 {
    job_at(workspace, "src/lib.rs", "J", VERSION)
}

fn lib(text: &str) -> u128 {
    of(&single(&[("src/lib.rs", text)]))
}

fn job(body: &str, rest: &str) -> u128 {
    lib(&source(body, rest))
}

